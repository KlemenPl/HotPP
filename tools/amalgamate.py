#!/usr/bin/env python3
"""Generates single_include/hotpp/hotpp.h: the public API plus the whole agent in
one header. Define HOTPP_IMPLEMENTATION in exactly one .cpp file before including it.

    tools/amalgamate.py            regenerate the header
    tools/amalgamate.py --check    exit 1 if the committed header is out of date
"""
import argparse
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "single_include" / "hotpp" / "hotpp.h"

PUBLIC = "include/hotpp/hotpp.h"
# Agent implementation, headers first, in dependency order.
IMPLEMENTATION = [
    "src/common/protocol.h",
    "src/common/messages.h",
    "src/common/endpoint.h",
    "src/agent/platform.h",
    "src/agent/region_select.h",
    "src/agent/patcher.h",
    "src/agent/region_select.cpp",
    "src/agent/platform_linux.cpp",
    "src/agent/threads_linux.cpp",
    "src/agent/jit_debug.cpp",
    "src/agent/patcher.cpp",
    "src/agent/agent.cpp",
]

LOCAL_INCLUDE = re.compile(r'^\s*#\s*include\s+"[^"]+"\s*$')
PRAGMA_ONCE = re.compile(r"^\s*#\s*pragma\s+once\s*$")


def body(path: str) -> str:
    lines = (ROOT / path).read_text().splitlines()
    kept = [l for l in lines if not LOCAL_INCLUDE.match(l) and not PRAGMA_ONCE.match(l)]
    return f"// ---- {path} " + "-" * max(0, 72 - len(path)) + "\n" + "\n".join(kept).strip("\n") + "\n"


def generate() -> str:
    parts = [
        "// HotPP: hot reload for C++ on Linux (x86-64, GCC and Clang).",
        "// Copyright (c) 2026 HotPP contributors",
        "// SPDX-License-Identifier: MIT (the license text is at the end of this file)",
        "// Single-header agent, generated by tools/amalgamate.py from the sources in",
        "// src/ and include/. Do not edit; edit those and regenerate.",
        "//",
        "// In exactly one .cpp file of your program (ideally one you rarely edit):",
        "//",
        "//     #define HOTPP_IMPLEMENTATION",
        "//     #include \"hotpp/hotpp.h\"",
        "//",
        "// Everywhere else, include it normally. Build with",
        "// -g -fpatchable-function-entry=7,5 (and -fno-ipa-icf with GCC), link with",
        "// -ldl -pthread, keep compile_commands.json in the build tree, and run the",
        "// program under the hotpp host. See README.md.",
        "",
        "#ifndef HOTPP_SINGLE_HEADER_H",
        "#define HOTPP_SINGLE_HEADER_H",
        "",
        body(PUBLIC),
        "#endif // HOTPP_SINGLE_HEADER_H",
        "",
        "#if defined(HOTPP_IMPLEMENTATION) && !defined(HOTPP_DISABLE) && !defined(HOTPP_IMPLEMENTATION_INCLUDED)",
        "#define HOTPP_IMPLEMENTATION_INCLUDED",
        "",
    ]
    parts += [body(p) for p in IMPLEMENTATION]
    parts += ["#endif // HOTPP_IMPLEMENTATION", ""]
    # The header is often copied into a project on its own, so it carries the
    # license with it.
    license_text = (ROOT / "LICENSE").read_text().strip("\n").splitlines()
    parts += ["/*"] + [("    " + l).rstrip() for l in license_text] + ["*/", ""]
    return "\n".join(parts)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    text = generate()
    if args.check:
        if not OUT.exists() or OUT.read_text() != text:
            print(f"{OUT.relative_to(ROOT)} is out of date; run tools/amalgamate.py")
            return 1
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)} ({len(text.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
